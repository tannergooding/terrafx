using System.Threading.Tasks;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Testing;
using NUnit.Framework;
using TerraFX.Diagnostics.Analyzers;
using AnalyzerTest = Microsoft.CodeAnalysis.CSharp.Testing.CSharpAnalyzerTest<TerraFX.Diagnostics.Analyzers.DocumentationCommentLayoutAnalyzer, Microsoft.CodeAnalysis.Testing.DefaultVerifier>;
using VerifyCS = Microsoft.CodeAnalysis.CSharp.Testing.CSharpAnalyzerVerifier<TerraFX.Diagnostics.Analyzers.DocumentationCommentLayoutAnalyzer, Microsoft.CodeAnalysis.Testing.DefaultVerifier>;

namespace TerraFX.Tests;

[TestFixture]
internal sealed class DocumentationCommentLayoutAnalyzerTests
{
    private static AnalyzerTest CreateTest(string source)
    {
        return new CSharp12AnalyzerTest {
            TestCode = source,
            ReferenceAssemblies = ReferenceAssemblies.Net.Net80,
        };
    }

    [Test]
    public async Task AcceptsAlignedMultilineStructuredElementsAsync()
    {
        var test = CreateTest(
            """
            class C
            {
                /// <summary>
                /// A summary with separate paragraphs.
                /// <para>Second paragraph.</para>
                /// </summary>
                public void M() { }
            }
            """);

        await test.RunAsync().ConfigureAwait(false);
    }

    [Test]
    public async Task AcceptsSingleLineElementsAsync()
    {
        var test = CreateTest(
            """
            class C
            {
                /// <summary>A concise summary.</summary>
                public void M() { }
            }
            """);

        await test.RunAsync().ConfigureAwait(false);
    }

    [Test]
    public async Task IgnoresGeneratedCodeAsync()
    {
        var test = CreateTest(
            """
            // <auto-generated />
            class C
            {
                /// <summary>
                /// A summary.
                /// </summary>
                public void M() { }
            }
            """);

        await test.RunAsync().ConfigureAwait(false);
    }

    [Test]
    public async Task ReportsMisalignedContinuationMarkersAsync()
    {
        var test = CreateTest(
            """
            class C
            {
                /// <remarks>
                 /// <para>A structured paragraph.</para>
                /// </remarks>
                public void M() { }
            }
            """);

        test.ExpectedDiagnostics.Add(VerifyCS.Diagnostic(DocumentationCommentLayoutAnalyzer.DiagnosticId).WithSpan(3, 8, 6, 1));

        await test.RunAsync().ConfigureAwait(false);
    }

    [Test]
    public async Task ReportsMultilineSingleParagraphElementsAsync()
    {
        var test = CreateTest(
            """
            class C
            {
                /// <summary>
                /// A concise summary.
                /// </summary>
                public void M() { }
            }
            """);

        test.ExpectedDiagnostics.Add(VerifyCS.Diagnostic(DocumentationCommentLayoutAnalyzer.DiagnosticId).WithSpan(3, 8, 6, 1));

        await test.RunAsync().ConfigureAwait(false);
    }

    private sealed class CSharp12AnalyzerTest : AnalyzerTest
    {
        protected override ParseOptions CreateParseOptions()
            => new CSharpParseOptions(LanguageVersion.CSharp12, DocumentationMode.Diagnose);
    }
}
