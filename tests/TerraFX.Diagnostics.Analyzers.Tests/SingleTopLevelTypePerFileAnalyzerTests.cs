using System.Threading.Tasks;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Testing;
using NUnit.Framework;
using TerraFX.Diagnostics.Analyzers;
using AnalyzerTest = Microsoft.CodeAnalysis.CSharp.Testing.CSharpAnalyzerTest<TerraFX.Diagnostics.Analyzers.SingleTopLevelTypePerFileAnalyzer, Microsoft.CodeAnalysis.Testing.DefaultVerifier>;
using VerifyCS = Microsoft.CodeAnalysis.CSharp.Testing.CSharpAnalyzerVerifier<TerraFX.Diagnostics.Analyzers.SingleTopLevelTypePerFileAnalyzer, Microsoft.CodeAnalysis.Testing.DefaultVerifier>;

namespace TerraFX.Tests;

[TestFixture]
internal sealed class SingleTopLevelTypePerFileAnalyzerTests
{
    private static AnalyzerTest CreateTest(string source)
    {
        return new CSharp12AnalyzerTest {
            TestCode = source,
            ReferenceAssemblies = ReferenceAssemblies.Net.Net80,
        };
    }

    [Test]
    public async Task AcceptsSingleTopLevelTypeAndNestedTypesAsync()
    {
        var test = CreateTest(
            """
            namespace Example;

            class Outer
            {
                struct Inner
                {
                    interface Nested
                    {
                    }
                }
            }
            """);

        await test.RunAsync().ConfigureAwait(false);
    }

    [Test]
    public async Task IgnoresGeneratedCodeAsync()
    {
        var test = CreateTest(
            """
            // <auto-generated />
            class First
            {
            }

            class Second
            {
            }
            """);

        await test.RunAsync().ConfigureAwait(false);
    }

    [Test]
    public async Task ReportsEveryAdditionalTypeKindAsync()
    {
        var test = CreateTest(
            """
            namespace First
            {
                class FirstType
                {
                    class NestedType
                    {
                    }
                }
            }

            namespace Second
            {
                struct {|#0:SecondType|}
                {
                }

                interface {|#1:ThirdType|}
                {
                }

                record {|#2:FourthType|};

                enum {|#3:FifthType|}
                {
                    Value
                }

                delegate void {|#4:SixthType|}();
            }
            """);

        test.ExpectedDiagnostics.Add(VerifyCS.Diagnostic(SingleTopLevelTypePerFileAnalyzer.DiagnosticId).WithLocation(0));
        test.ExpectedDiagnostics.Add(VerifyCS.Diagnostic(SingleTopLevelTypePerFileAnalyzer.DiagnosticId).WithLocation(1));
        test.ExpectedDiagnostics.Add(VerifyCS.Diagnostic(SingleTopLevelTypePerFileAnalyzer.DiagnosticId).WithLocation(2));
        test.ExpectedDiagnostics.Add(VerifyCS.Diagnostic(SingleTopLevelTypePerFileAnalyzer.DiagnosticId).WithLocation(3));
        test.ExpectedDiagnostics.Add(VerifyCS.Diagnostic(SingleTopLevelTypePerFileAnalyzer.DiagnosticId).WithLocation(4));

        await test.RunAsync().ConfigureAwait(false);
    }

    [Test]
    public async Task ReportsFileWithoutTypeDeclarationAsync()
    {
        var test = CreateTest("using System;");

        test.ExpectedDiagnostics.Add(VerifyCS.Diagnostic(SingleTopLevelTypePerFileAnalyzer.DiagnosticId).WithSpan(1, 1, 1, 14));

        await test.RunAsync().ConfigureAwait(false);
    }

    private sealed class CSharp12AnalyzerTest : AnalyzerTest
    {
        protected override ParseOptions CreateParseOptions()
            => new CSharpParseOptions(LanguageVersion.CSharp12, DocumentationMode.Diagnose);
    }
}
