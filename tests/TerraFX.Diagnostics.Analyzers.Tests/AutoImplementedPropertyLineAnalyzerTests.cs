using System.Threading.Tasks;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Testing;
using NUnit.Framework;
using TerraFX.Diagnostics.Analyzers;
using AnalyzerTest = Microsoft.CodeAnalysis.CSharp.Testing.CSharpAnalyzerTest<TerraFX.Diagnostics.Analyzers.AutoImplementedPropertyLineAnalyzer, Microsoft.CodeAnalysis.Testing.DefaultVerifier>;
using VerifyCS = Microsoft.CodeAnalysis.CSharp.Testing.CSharpAnalyzerVerifier<TerraFX.Diagnostics.Analyzers.AutoImplementedPropertyLineAnalyzer, Microsoft.CodeAnalysis.Testing.DefaultVerifier>;

namespace TerraFX.Tests;

[TestFixture]
internal sealed class AutoImplementedPropertyLineAnalyzerTests
{
    private static AnalyzerTest CreateTest(string source)
    {
        return new CSharp12AnalyzerTest {
            TestCode = source,
            ReferenceAssemblies = ReferenceAssemblies.Net.Net80,
        };
    }

    [Test]
    public async Task AcceptsMultilineExpressionBodiedAndCustomAccessorPropertiesAsync()
    {
        var test = CreateTest(
            """
            class C
            {
                private int _value;

                public int ExpressionBodied
                    => _value;

                public int CustomAccessor
                {
                    get
                    {
                        return _value;
                    }
                    set
                    {
                        _value = value;
                    }
                }
            }
            """);

        await test.RunAsync().ConfigureAwait(false);
    }

    [Test]
    public async Task AcceptsOneLineAutoImplementedPropertyAsync()
    {
        var test = CreateTest(
            """
            class C
            {
                public int Value { get; private set; }
            }
            """);

        await test.RunAsync().ConfigureAwait(false);
    }

    [Test]
    public async Task IgnoresGeneratedCodeAsync()
    {
        var test = CreateTest(
            """
            // <auto-generated />
            class C
            {
                public int Value
                {
                    get;
                }
            }
            """);

        await test.RunAsync().ConfigureAwait(false);
    }

    [Test]
    public async Task ReportsMultilineAutoImplementedPropertyAsync()
    {
        var test = CreateTest(
            """
            class C
            {
                {|#0:public int Value
                {
                    get;
                    private set;
                }|}
            }
            """);

        test.ExpectedDiagnostics.Add(VerifyCS.Diagnostic(AutoImplementedPropertyLineAnalyzer.DiagnosticId).WithLocation(0));

        await test.RunAsync().ConfigureAwait(false);
    }

    private sealed class CSharp12AnalyzerTest : AnalyzerTest
    {
        protected override ParseOptions CreateParseOptions()
            => new CSharpParseOptions(LanguageVersion.CSharp12, DocumentationMode.Diagnose);
    }
}
