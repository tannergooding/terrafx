using System;
using System.Globalization;
using System.Security.Cryptography;
using System.Text;
using System.Threading;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace TerraFX.Generators;

/// <summary>Generates the fixed ObjectGpuData byte packer for its concrete Runtime consumer.</summary>
[Generator(LanguageNames.CSharp)]
public sealed class ObjectGpuDataGenerator : IIncrementalGenerator
{
    private const string MarkerName = "TerraFX.Generators.GenerateObjectGpuDataPackerAttribute";

    private static void AppendFloatWrite(StringBuilder builder, string indent, int offset, string value)
        => _ = builder.Append(indent)
            .Append("WriteSingle(destination, ")
            .Append(offset.ToString(CultureInfo.InvariantCulture))
            .Append(", ")
            .Append(value)
            .Append(");\n");

    private static string CreateHintName(INamedTypeSymbol target)
    {
        var identity = target.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        using var sha256 = SHA256.Create();
        var hashBytes = sha256.ComputeHash(Encoding.UTF8.GetBytes(identity));
        var hash = new StringBuilder(hashBytes.Length * 2);

        foreach (var value in hashBytes)
        {
            _ = hash.Append(value.ToString("x2", CultureInfo.InvariantCulture));
        }

        return string.Concat("TerraFX.ObjectGpuDataPacker.", hash, ".g.cs");
    }

    private static GeneratedOutput CreateOutput(
        GeneratorAttributeSyntaxContext context,
        CancellationToken cancellationToken)
    {
        cancellationToken.ThrowIfCancellationRequested();

        if (context.TargetSymbol is not INamedTypeSymbol target
            || (target.TypeKind != TypeKind.Struct)
            || target.IsRecord
            || target.IsGenericType
            || target.IsReadOnly != true
            || (target.DeclaredAccessibility != Accessibility.Internal)
            || (target.ContainingType is not null)
            || (target.Name != "ObjectGpuData")
            || !HasPartialDeclaration(target, cancellationToken)
            || !HasExpectedFields(target))
        {
            var hintName = context.TargetSymbol is INamedTypeSymbol namedTarget
                ? CreateHintName(namedTarget)
                : "TerraFX.ObjectGpuDataPacker.invalid.g.cs";

            return new GeneratedOutput(
                hintName,
                "// <auto-generated />\n#error ObjectGpuData must be an internal readonly partial struct with the fixed field contract.\n");
        }

        var source = Emit(target, cancellationToken);
        return new GeneratedOutput(CreateHintName(target), source);
    }

    private static string Emit(INamedTypeSymbol target, CancellationToken cancellationToken)
    {
        var builder = new StringBuilder();
        _ = builder.Append("// <auto-generated />\n#nullable enable\n");

        if (!target.ContainingNamespace.IsGlobalNamespace)
        {
            _ = builder.Append("namespace ").Append(GetEscapedNamespace(target.ContainingNamespace)).Append("\n{\n");
        }

        var indent = target.ContainingNamespace.IsGlobalNamespace ? string.Empty : "    ";
        _ = builder.Append(indent).Append("internal readonly partial struct ObjectGpuData\n")
            .Append(indent).Append("{\n");
        indent += "    ";
        _ = builder.Append(indent).Append("internal const int SizeInBytes = 192;\n\n")
            .Append(indent).Append("internal void WriteTo(global::System.Span<byte> destination)\n")
            .Append(indent).Append("{\n")
            .Append(indent).Append("    if (destination.Length < SizeInBytes)\n")
            .Append(indent).Append("    {\n")
            .Append(indent).Append("        throw new global::System.ArgumentException(\"The destination is smaller than the ObjectGpuData record.\", nameof(destination));\n")
            .Append(indent).Append("    }\n\n");

        var outputIndent = string.Concat(indent, "    ");
        var offset = 0;

        for (var fieldIndex = 0; fieldIndex < 5; fieldIndex++)
        {
            var fieldName = GetFloatFieldName(fieldIndex);
            cancellationToken.ThrowIfCancellationRequested();
            var field = FindField(target, fieldName);

            if (field is null)
            {
                continue;
            }

            if (fieldName is "_world" or "_previousWorld")
            {
                for (var rowIndex = 0; rowIndex < 4; rowIndex++)
                {
                    var rowName = $"Row{rowIndex + 1}";

                    foreach (var componentName in new[] { "X", "Y", "Z", "W" })
                    {
                        AppendFloatWrite(builder, outputIndent, offset, string.Concat(fieldName, ".", rowName, ".", componentName));
                        offset += sizeof(float);
                    }
                }
            }
            else
            {
                foreach (var componentName in new[] { "X", "Y", "Z", "W" })
                {
                    AppendFloatWrite(builder, outputIndent, offset, string.Concat(fieldName, ".", componentName));
                    offset += sizeof(float);
                }
            }
        }

        _ = builder.Append(outputIndent).Append("WriteUInt32(destination, 176, _metadata0);\n")
            .Append(outputIndent).Append("WriteUInt32(destination, 180, _metadata1);\n")
            .Append(outputIndent).Append("WriteUInt32(destination, 184, _metadata2);\n")
            .Append(outputIndent).Append("WriteUInt32(destination, 188, _metadata3);\n")
            .Append(indent).Append("}\n\n")
            .Append(indent).Append("internal static global::TerraFX.Numerics.Vector4 Direction(global::TerraFX.Numerics.Vector3 value)\n")
            .Append(indent).Append("    => new global::TerraFX.Numerics.Vector4(value, 0.0f);\n\n")
            .Append(indent).Append("internal static global::TerraFX.Numerics.Vector4 Position(global::TerraFX.Numerics.Vector3 value)\n")
            .Append(indent).Append("    => new global::TerraFX.Numerics.Vector4(value, 1.0f);\n\n")
            .Append(indent).Append("internal static int GetUniformAllocationStride(int vulkanAlignment)\n")
            .Append(indent).Append("{\n")
            .Append(indent).Append("    global::System.ArgumentOutOfRangeException.ThrowIfNegativeOrZero(vulkanAlignment);\n")
            .Append(indent).Append("    var commonDivisor = GreatestCommonDivisor(256, vulkanAlignment);\n")
            .Append(indent).Append("    var alignment = checked((256 / commonDivisor) * vulkanAlignment);\n")
            .Append(indent).Append("    return checked(((SizeInBytes + alignment - 1) / alignment) * alignment);\n")
            .Append(indent).Append("}\n\n")
            .Append(indent).Append("private static int GreatestCommonDivisor(int left, int right)\n")
            .Append(indent).Append("{\n")
            .Append(indent).Append("    while (right != 0)\n")
            .Append(indent).Append("    {\n")
            .Append(indent).Append("        var remainder = left % right;\n")
            .Append(indent).Append("        left = right;\n")
            .Append(indent).Append("        right = remainder;\n")
            .Append(indent).Append("    }\n\n")
            .Append(indent).Append("    return left;\n")
            .Append(indent).Append("}\n\n")
            .Append(indent).Append("private static void WriteSingle(global::System.Span<byte> destination, int offset, float value)\n")
            .Append(indent).Append("    => global::System.Runtime.InteropServices.MemoryMarshal.Write(destination.Slice(offset, sizeof(float)), in value);\n\n")
            .Append(indent).Append("private static void WriteUInt32(global::System.Span<byte> destination, int offset, uint value)\n")
            .Append(indent).Append("    => global::System.Runtime.InteropServices.MemoryMarshal.Write(destination.Slice(offset, sizeof(uint)), in value);\n");
        indent = indent.Substring(0, indent.Length - 4);
        _ = builder.Append(indent).Append("}\n");

        if (!target.ContainingNamespace.IsGlobalNamespace)
        {
            _ = builder.Append("}\n");
        }

        return builder.ToString();
    }

    private static string EscapeIdentifier(string value)
        => SyntaxFacts.GetKeywordKind(value) == SyntaxKind.None ? value : string.Concat("@", value);

    private static IFieldSymbol? FindField(INamedTypeSymbol target, string name)
    {
        foreach (var member in target.GetMembers(name))
        {
            if (member is IFieldSymbol field)
            {
                return field;
            }
        }

        return null;
    }

    private static string GetEscapedNamespace(INamespaceSymbol @namespace)
    {
        var current = EscapeIdentifier(@namespace.Name);
        return @namespace.ContainingNamespace.IsGlobalNamespace
            ? current
            : string.Concat(GetEscapedNamespace(@namespace.ContainingNamespace), ".", current);
    }

    private static string GetFloatFieldName(int index)
        => index switch {
            0 => "_world",
            1 => "_previousWorld",
            2 => "_normalRow0",
            3 => "_normalRow1",
            4 => "_normalRow2",
            _ => throw new ArgumentOutOfRangeException(nameof(index))
        };

    private static bool HasExpectedFields(INamedTypeSymbol target)
    {
        var instanceFieldCount = 0;

        foreach (var member in target.GetMembers())
        {
            if (member is IFieldSymbol field && !field.IsStatic)
            {
                instanceFieldCount++;
            }
        }

        if (instanceFieldCount != 9)
        {
            return false;
        }

        for (var fieldIndex = 0; fieldIndex < 5; fieldIndex++)
        {
            var fieldName = GetFloatFieldName(fieldIndex);
            var field = FindField(target, fieldName);
            var expectedType = fieldName is "_world" or "_previousWorld"
                ? "global::TerraFX.Numerics.Matrix4x4"
                : "global::TerraFX.Numerics.Vector4";

            if (field is null
                || field.IsStatic
                || !field.IsReadOnly
                || (field.DeclaredAccessibility != Accessibility.Private)
                || (field.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) != expectedType))
            {
                return false;
            }
        }

        for (var index = 0; index < 4; index++)
        {
            var field = FindField(target, string.Concat("_metadata", index.ToString(CultureInfo.InvariantCulture)));

            if (field is null
                || field.IsStatic
                || !field.IsReadOnly
                || (field.DeclaredAccessibility != Accessibility.Private)
                || (field.Type.SpecialType != SpecialType.System_UInt32))
            {
                return false;
            }
        }

        return true;
    }

    private static bool HasPartialDeclaration(INamedTypeSymbol type, CancellationToken cancellationToken)
    {
        foreach (var syntaxReference in type.DeclaringSyntaxReferences)
        {
            cancellationToken.ThrowIfCancellationRequested();

            if (syntaxReference.GetSyntax(cancellationToken) is not StructDeclarationSyntax declaration
                || !declaration.Modifiers.Any(SyntaxKind.PartialKeyword))
            {
                return false;
            }
        }

        return type.DeclaringSyntaxReferences.Length != 0;
    }

    /// <inheritdoc/>
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(static postInitializationContext => {
            postInitializationContext.AddEmbeddedAttributeDefinition();
            postInitializationContext.AddSource(
                "TerraFX.ObjectGpuDataGenerator.Attribute.g.cs",
                SourceText.From(
                    """
                    // <auto-generated />
                    #nullable enable
                    namespace TerraFX.Generators
                    {
                        [global::Microsoft.CodeAnalysis.Embedded]
                        [global::System.AttributeUsage(global::System.AttributeTargets.Struct, Inherited = false, AllowMultiple = false)]
                        internal sealed class GenerateObjectGpuDataPackerAttribute : global::System.Attribute
                        {
                        }
                    }
                    """,
                    Encoding.UTF8));
        });

        var outputs = context.SyntaxProvider.ForAttributeWithMetadataName(
                MarkerName,
                static (node, _) => node is StructDeclarationSyntax,
                static (attributeContext, cancellationToken) => CreateOutput(attributeContext, cancellationToken))
            .WithTrackingName("TerraFX.ObjectGpuDataPackerModel");

        context.RegisterSourceOutput(
            outputs,
            static (productionContext, output) =>
                productionContext.AddSource(output.HintName, SourceText.From(output.Source, Encoding.UTF8)));
    }

    private readonly struct GeneratedOutput : IEquatable<GeneratedOutput>
    {
        internal GeneratedOutput(string hintName, string source)
        {
            HintName = hintName;
            Source = source;
        }

        internal string HintName { get; }

        internal string Source { get; }

        public bool Equals(GeneratedOutput other)
            => StringComparer.Ordinal.Equals(HintName, other.HintName)
            && StringComparer.Ordinal.Equals(Source, other.Source);

        public override bool Equals(object? obj)
            => obj is GeneratedOutput other && Equals(other);

        public override int GetHashCode()
            => unchecked((StringComparer.Ordinal.GetHashCode(HintName) * 397) ^ StringComparer.Ordinal.GetHashCode(Source));
    }
}
