using System;
using System.Collections.Generic;
using System.Globalization;
using System.Security.Cryptography;
using System.Text;
using System.Threading;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace TerraFX.Generators;

/// <summary>Generates typed component accessors and explicit semantic/storage paths.</summary>
[Generator(LanguageNames.CSharp)]
public sealed class ComponentAccessorGenerator : IIncrementalGenerator
{
    private const string ComponentBindingsAttributeName = "TerraFX.Generators.GenerateComponentBindingsAttribute";
    private const string ComponentFieldAccessorAttributeName = "TerraFX.Generators.GenerateComponentFieldAccessorAttribute";

    private static GeneratedOutput CreateErrorOutput(string message, string hintName)
        => new(hintName, string.Concat("// <auto-generated />\n#error ", message, "\n"));

    private static string CreateHintName(INamedTypeSymbol component)
    {
        var identity = component.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        var safeIdentity = new StringBuilder(identity.Length);

        foreach (var character in identity)
        {
            _ = safeIdentity.Append(char.IsLetterOrDigit(character) ? character : '_');
        }

        using var sha256 = SHA256.Create();
        var hashBytes = sha256.ComputeHash(Encoding.UTF8.GetBytes(identity));
        var hash = new StringBuilder(hashBytes.Length * 2);

        foreach (var value in hashBytes)
        {
            _ = hash.Append(value.ToString("x2", CultureInfo.InvariantCulture));
        }

        return string.Concat("TerraFX.ComponentBindings.", safeIdentity, ".", hash, ".g.cs");
    }

    private static GeneratedOutput CreateOutput(
        GeneratorAttributeSyntaxContext context,
        CancellationToken cancellationToken)
    {
        cancellationToken.ThrowIfCancellationRequested();

        if (context.TargetSymbol is not INamedTypeSymbol component)
        {
            return CreateErrorOutput("The component binding marker must annotate a struct.", "TerraFX.ComponentBindings.invalid.g.cs");
        }

        if ((component.TypeKind != TypeKind.Struct)
            || component.IsRecord
            || component.IsGenericType
            || !HasPartialDeclaration(component, cancellationToken))
        {
            return CreateErrorOutput(
                "The component binding target must be a non-generic partial struct.",
                CreateHintName(component));
        }

        var containingType = component.ContainingType;

        if ((containingType is null)
            || (containingType.TypeKind != TypeKind.Class)
            || !containingType.IsStatic
            || containingType.IsGenericType
            || !HasPartialDeclaration(containingType, cancellationToken)
            || (containingType.ContainingType is not null))
        {
            return CreateErrorOutput(
                "Generated component accessors require one non-generic static partial containing class.",
                CreateHintName(component));
        }

        INamedTypeSymbol? authorType = null;

        foreach (var attribute in context.Attributes)
        {
            if ((attribute.AttributeClass?.ToDisplayString() == ComponentBindingsAttributeName)
                && (attribute.ConstructorArguments.Length == 1)
                && (attribute.ConstructorArguments[0].Value is INamedTypeSymbol authorTypeValue))
            {
                authorType = authorTypeValue;
                break;
            }
        }

        if ((authorType is null)
            || !authorType.IsValueType
            || authorType.IsGenericType
            || !SymbolEqualityComparer.Default.Equals(authorType.ContainingType, containingType))
        {
            return CreateErrorOutput(
                "The component binding marker must name a closed author value type in the same containing class.",
                CreateHintName(component));
        }

        var fields = new List<FieldModel>();
        var fieldTags = new HashSet<uint>();
        var storagePaths = new HashSet<string>(StringComparer.Ordinal);

        foreach (var member in component.GetMembers())
        {
            cancellationToken.ThrowIfCancellationRequested();

            if (member is not IFieldSymbol field)
            {
                continue;
            }

            foreach (var attribute in field.GetAttributes())
            {
                cancellationToken.ThrowIfCancellationRequested();

                if (attribute.AttributeClass?.ToDisplayString() != ComponentFieldAccessorAttributeName)
                {
                    continue;
                }

                if ((attribute.ConstructorArguments.Length != 3)
                    || (attribute.ConstructorArguments[0].Value is not uint fieldTag)
                    || (attribute.ConstructorArguments[1].Value is not string authorMemberName)
                    || (attribute.ConstructorArguments[2].Value is not string storageMemberName)
                    || (fieldTag == 0)
                    || string.IsNullOrEmpty(authorMemberName)
                    || !IsValidStorageMemberName(storageMemberName)
                    || field.IsStatic
                    || field.IsReadOnly
                    || !field.Type.IsUnmanagedType
                    || !fieldTags.Add(fieldTag)
                    || !storagePaths.Add(storageMemberName))
                {
                    return CreateErrorOutput(
                        "A generated component field requires a unique positive tag, distinct storage member, mutable unmanaged instance field, and nonempty author/storage names.",
                        CreateHintName(component));
                }

                var authorMember = GetAuthorMember(authorType, authorMemberName);

                if ((authorMember is null)
                    || !SymbolEqualityComparer.Default.Equals(GetMemberType(authorMember), field.Type))
                {
                    return CreateErrorOutput(
                        "The generated component field must map to exactly one author field or property of the same type.",
                        CreateHintName(component));
                }

                fields.Add(new FieldModel(
                    fieldTag,
                    EscapeIdentifier(field.Name),
                    field.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat),
                    authorMemberName,
                    storageMemberName));
            }
        }

        if (fields.Count == 0)
        {
            return CreateErrorOutput(
                "A generated component binding requires at least one annotated field.",
                CreateHintName(component));
        }

        fields.Sort(static (left, right) => left.FieldTag.CompareTo(right.FieldTag));
        return new GeneratedOutput(
            CreateHintName(component),
            Emit(component, containingType, authorType, fields, cancellationToken));
    }

    private static string Emit(
        INamedTypeSymbol component,
        INamedTypeSymbol containingType,
        INamedTypeSymbol authorType,
        List<FieldModel> fields,
        CancellationToken cancellationToken)
    {
        var builder = new StringBuilder();
        _ = builder.Append("// <auto-generated />\n");
        _ = builder.Append("#nullable enable\n");
        var namespaceName = component.ContainingNamespace.ToDisplayString();

        if (!component.ContainingNamespace.IsGlobalNamespace)
        {
            _ = builder.Append("namespace ").Append(namespaceName).Append('\n');
            _ = builder.Append("{\n");
        }

        var indent = component.ContainingNamespace.IsGlobalNamespace ? string.Empty : "    ";
        _ = builder.Append(indent)
            .Append(GetAccessibility(containingType.DeclaredAccessibility))
            .Append(' ')
            .Append(containingType.IsStatic ? "static " : string.Empty)
            .Append("partial class ")
            .Append(EscapeIdentifier(containingType.Name))
            .Append('\n');
        _ = builder.Append(indent).Append("{\n");
        indent += "    ";
        _ = builder.Append(indent)
            .Append(GetAccessibility(component.DeclaredAccessibility))
            .Append(" partial struct ")
            .Append(EscapeIdentifier(component.Name))
            .Append('\n');
        _ = builder.Append(indent).Append("{\n");
        indent += "    ";

        var componentTypeName = component.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        var authorTypeName = authorType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);

        foreach (var field in fields)
        {
            cancellationToken.ThrowIfCancellationRequested();
            var suffix = field.FieldTag.ToString(CultureInfo.InvariantCulture);
            _ = builder.Append(indent)
                .Append("internal static global::TerraFX.Entities.ComponentFieldPath Field")
                .Append(suffix)
                .Append("FieldPath { get; } = new global::TerraFX.Entities.ComponentFieldPath(global::System.Collections.Immutable.ImmutableArray.Create(global::TerraFX.Entities.ComponentPropertySegment.FieldTag(")
                .Append(suffix)
                .Append("u)));\n");
            _ = builder.Append(indent)
                .Append("internal static global::TerraFX.Entities.ComponentStoragePath Field")
                .Append(suffix)
                .Append("StoragePath { get; } = new global::TerraFX.Entities.ComponentStoragePath(global::System.Collections.Immutable.ImmutableArray.Create(global::TerraFX.Entities.ComponentStorageSegment.Member(")
                .Append(SymbolDisplay.FormatLiteral(field.StorageMemberName, quote: true))
                .Append(")));\n");
            _ = builder.Append(indent)
                .Append("internal readonly struct Field")
                .Append(suffix)
                .Append("Accessor : global::TerraFX.Entities.IComponentValueAccessor<")
                .Append(componentTypeName)
                .Append(", ")
                .Append(field.ValueTypeName)
                .Append(">\n");
            _ = builder.Append(indent).Append("{\n");
            _ = builder.Append(indent)
                .Append("    public ")
                .Append(field.ValueTypeName)
                .Append(" Get(in ")
                .Append(componentTypeName)
                .Append(" value) => value.")
                .Append(field.FieldName)
                .Append(";\n");
            _ = builder.Append(indent)
                .Append("    public void Set(ref ")
                .Append(componentTypeName)
                .Append(" value, in ")
                .Append(field.ValueTypeName)
                .Append(" fieldValue) => value.")
                .Append(field.FieldName)
                .Append(" = fieldValue;\n");
            _ = builder.Append(indent).Append("}\n");
            _ = builder.Append(indent)
                .Append("internal readonly struct Field")
                .Append(suffix)
                .Append("Reader : global::TerraFX.Entities.IComponentValueReader<")
                .Append(authorTypeName)
                .Append(", ")
                .Append(field.ValueTypeName)
                .Append(">\n");
            _ = builder.Append(indent).Append("{\n");
            _ = builder.Append(indent)
                .Append("    public ")
                .Append(field.ValueTypeName)
                .Append(" Get(in ")
                .Append(authorTypeName)
                .Append(" value) => value.")
                .Append(EscapeIdentifier(field.AuthorMemberName))
                .Append(";\n");
            _ = builder.Append(indent).Append("}\n");
        }

        indent = indent.Substring(0, indent.Length - 4);
        _ = builder.Append(indent).Append("}\n");
        indent = indent.Substring(0, indent.Length - 4);
        _ = builder.Append(indent).Append("}\n");

        if (!component.ContainingNamespace.IsGlobalNamespace)
        {
            _ = builder.Append("}\n");
        }

        return builder.ToString();
    }

    private static string EscapeIdentifier(string value)
        => SyntaxFacts.GetKeywordKind(value) == SyntaxKind.None ? value : string.Concat("@", value);

    private static string GetAccessibility(Accessibility accessibility)
        => accessibility switch {
            Accessibility.Public => "public",
            Accessibility.Internal => "internal",
            Accessibility.Private => "private",
            Accessibility.Protected => "protected",
            Accessibility.ProtectedOrInternal => "protected internal",
            Accessibility.ProtectedAndInternal => "private protected",
            _ => "internal",
        };

    private static ISymbol? GetAuthorMember(INamedTypeSymbol authorType, string authorMemberName)
    {
        ISymbol? result = null;

        foreach (var member in authorType.GetMembers(authorMemberName))
        {
            var isReadableInstanceMember = member switch {
                IPropertySymbol property => !property.IsStatic && (property.GetMethod is not null) && property.Parameters.IsEmpty,
                IFieldSymbol field => !field.IsStatic,
                _ => false,
            };

            if (!isReadableInstanceMember || (result is not null))
            {
                continue;
            }

            result = member;
        }

        return result;
    }

    private static ITypeSymbol? GetMemberType(ISymbol member)
        => member switch {
            IPropertySymbol property => property.Type,
            IFieldSymbol field => field.Type,
            _ => null,
        };

    private static bool HasPartialDeclaration(INamedTypeSymbol type, CancellationToken cancellationToken)
    {
        foreach (var syntaxReference in type.DeclaringSyntaxReferences)
        {
            cancellationToken.ThrowIfCancellationRequested();

            if (syntaxReference.GetSyntax(cancellationToken) is not TypeDeclarationSyntax declaration
                || !declaration.Modifiers.Any(SyntaxKind.PartialKeyword))
            {
                return false;
            }
        }

        return type.DeclaringSyntaxReferences.Length != 0;
    }

    private static bool IsValidStorageMemberName(string value)
    {
        if (value.Length is 0 or > 128)
        {
            return false;
        }

        var utf8ByteCount = 0;

        for (var index = 0; index < value.Length; index++)
        {
            var character = value[index];

            if (char.IsHighSurrogate(character))
            {
                if ((index + 1 >= value.Length) || !char.IsLowSurrogate(value[index + 1]))
                {
                    return false;
                }

                utf8ByteCount = checked(utf8ByteCount + 4);
                index++;
            }
            else if (char.IsLowSurrogate(character))
            {
                return false;
            }
            else
            {
                utf8ByteCount = checked(utf8ByteCount + ((character <= 0x7F) ? 1 : (character <= 0x7FF) ? 2 : 3));
            }

            if (utf8ByteCount > 128)
            {
                return false;
            }
        }

        return true;
    }

    /// <inheritdoc/>
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(static postInitializationContext => {
            postInitializationContext.AddEmbeddedAttributeDefinition();
            postInitializationContext.AddSource(
                "TerraFX.ComponentAccessorGenerator.Attributes.g.cs",
                SourceText.From(
                    """
                    // <auto-generated />
                    #nullable enable
                    namespace TerraFX.Generators
                    {
                        [global::Microsoft.CodeAnalysis.Embedded]
                        [global::System.AttributeUsage(global::System.AttributeTargets.Struct, Inherited = false, AllowMultiple = false)]
                        internal sealed class GenerateComponentBindingsAttribute : global::System.Attribute
                        {
                            public GenerateComponentBindingsAttribute(global::System.Type authorType)
                            {
                                AuthorType = authorType;
                            }

                            public global::System.Type AuthorType { get; }
                        }

                        [global::Microsoft.CodeAnalysis.Embedded]
                        [global::System.AttributeUsage(global::System.AttributeTargets.Field, Inherited = false, AllowMultiple = false)]
                        internal sealed class GenerateComponentFieldAccessorAttribute : global::System.Attribute
                        {
                            public GenerateComponentFieldAccessorAttribute(
                                uint fieldTag,
                                string authorMemberName,
                                string storageMemberName)
                            {
                                FieldTag = fieldTag;
                                AuthorMemberName = authorMemberName;
                                StorageMemberName = storageMemberName;
                            }

                            public uint FieldTag { get; }

                            public string AuthorMemberName { get; }

                            public string StorageMemberName { get; }
                        }
                    }
                    """,
                    Encoding.UTF8));
        });

        var outputs = context.SyntaxProvider.ForAttributeWithMetadataName(
                ComponentBindingsAttributeName,
                static (node, _) => node is StructDeclarationSyntax,
                static (attributeContext, cancellationToken) => CreateOutput(attributeContext, cancellationToken))
            .WithTrackingName("TerraFX.ComponentAccessorModel");

        context.RegisterSourceOutput(
            outputs,
            static (productionContext, output) =>
                productionContext.AddSource(output.HintName, SourceText.From(output.Source, Encoding.UTF8)));
    }

    private sealed class FieldModel
    {
        internal FieldModel(
            uint fieldTag,
            string fieldName,
            string valueTypeName,
            string authorMemberName,
            string storageMemberName)
        {
            FieldTag = fieldTag;
            FieldName = fieldName;
            ValueTypeName = valueTypeName;
            AuthorMemberName = authorMemberName;
            StorageMemberName = storageMemberName;
        }

        internal string AuthorMemberName { get; }

        internal string FieldName { get; }

        internal uint FieldTag { get; }

        internal string StorageMemberName { get; }

        internal string ValueTypeName { get; }
    }

    private readonly struct GeneratedOutput : IEquatable<GeneratedOutput>
    {
        internal GeneratedOutput(string hintName, string source)
        {
            HintName = hintName;
            Source = source;
        }

        internal string HintName { get; }

        internal string Source { get; }

        public bool Equals(GeneratedOutput other)
            => StringComparer.Ordinal.Equals(HintName, other.HintName)
            && StringComparer.Ordinal.Equals(Source, other.Source);

        public override bool Equals(object? obj)
            => obj is GeneratedOutput other && Equals(other);

        public override int GetHashCode()
            => unchecked((StringComparer.Ordinal.GetHashCode(HintName) * 397) ^ StringComparer.Ordinal.GetHashCode(Source));
    }
}
